import { LIMITS } from "./constants.js";
import { TYPES, agentPayDomain, scorerDomain, typeHash, type PrimaryType } from "./eip712.js";
import { merkleProof, openNonce, receiptLeaf, receiptsRoot, requestHash, sessionId, specHash, ZERO_HASH } from "./hash.js";
import type { OpenParams, PolicyParams, ScoreAttestation, SessionVerdict, Voucher } from "./types.js";

/** Fixed inputs shared with contracts/test/AgentPayFreeze.t.sol. Changing them = regenerate vectors. */
export const VECTOR_INPUT = {
  chainId: 43113,
  escrow: "0x00000000000000000000000000000000000e5c40" as Address,
  buyer: "0x318480ac2dd10427E6B866f57656ab4f41412bB7" as Address,
  salt: "0x1111111111111111111111111111111111111111111111111111111111111111" as Hex,
  params: {
    seller: "0x000df72153A7759980C5b427302aB8ae724E85b1",
    sellerAgentId: 12n,
    verifier: "0x7C06cef00c06455a7d0Dd91A10732b46F9Ea1FAA",
    voucherSigner: "0x318480ac2dd10427E6B866f57656ab4f41412bB7",
    specHash: "0x2222222222222222222222222222222222222222222222222222222222222222",
    cap: 5_000_000n,
    pricePerRequest: 10_000n,
    expiry: 1_800_000_000n,
    deliveryDeadlineSec: 10,
    challengeWindowSec: 60,
  } satisfies OpenParams,
  request: { method: "GET", url: "https://seller.example/v1/price/AVAX" },
  spec: { b: 1, a: [true, null, "x"], c: { z: 1.5, y: "ü" } },
} as const;

export function buildFreezeVectors() {
  const v = VECTOR_INPUT;
  const nonce = openNonce(v.params, v.salt);
  const sid = sessionId(v.buyer, nonce);
  const domain = agentPayDomain(v.chainId, v.escrow);

  const voucher: Voucher = {
    sessionId: sid,
    seq: 3,
    cumulativeAmount: 30_000n,
    requestHash: requestHash(v.request.method, v.request.url),
  };
  const verdict: SessionVerdict = {
    sessionId: sid,
    specHash: v.params.specHash,
    lastSeq: 3,
    passCount: 2,
    failCount: 1,
    inconclusiveCount: 0,
    passedAmount: 20_000n,
    receiptsRoot: "0x3333333333333333333333333333333333333333333333333333333333333333",
    closedAt: 1_799_999_000n,
  };
  const att: ScoreAttestation = {
    agentId: 12n,
    wallet: v.params.seller,
    score: 72,
    flags: 0,
    validUntil: 1_799_999_999n,
  };
  const policy: PolicyParams = {
    maxPerSession: 5_000_000n,
    dailyCap: 20_000_000n,
    minScore: 50,
    paused: false,
    sellerAllowlistOn: true,
  };

  const typehashes = Object.fromEntries(
    (Object.keys(TYPES) as PrimaryType[]).map((k) => [k, typeHash(k)]),
  ) as Record<PrimaryType, Hex>;

  const delivery = { sessionId: sid, seq: 3, requestHash: voucher.requestHash, bodyHash: v.salt, specHash: v.params.specHash };
  const receipts = Array.from({ length: 5 }, (_, index) => ({
    sessionId: sid, seq: index + 1, requestHash: voucher.requestHash, bodyHash: v.salt,
    outcome: 1, reasonCode: 0, amount: v.params.pricePerRequest, receivedAt: 1_799_999_000n, evidenceHash: ZERO_HASH,
  }));
  const deadline = v.params.expiry;

  return {
    note: "Generated by packages/agentpay-core (pnpm gen:vectors). Do not edit by hand.",
    typehashes,
    constants: Object.fromEntries(Object.entries(LIMITS).map(([k, val]) => [k, val.toString()])),
    openNonce: nonce,
    sessionId: sid.toString(),
    requestHash: voucher.requestHash,
    specHashJcs: specHash(v.spec as Record<string, unknown>),
    voucherDigest: hashTypedData({ domain, types: TYPES.Voucher, primaryType: "Voucher", message: voucher }),
    deliveryDigest: hashTypedData({ domain, types: TYPES.Delivery, primaryType: "Delivery", message: delivery }),
    receiptDigest: hashTypedData({ domain, types: TYPES.Receipt, primaryType: "Receipt", message: receipts[2]! }),
    closeRequestDigest: hashTypedData({ domain, types: TYPES.CloseRequest, primaryType: "CloseRequest", message: { sessionId: sid, deadline } }),
    pauseBuyerDigest: hashTypedData({ domain, types: TYPES.PauseBuyer, primaryType: "PauseBuyer", message: { buyer: v.buyer, nonce: 1n, deadline } }),
    receiptsRoot: receiptsRoot(receipts),
    thirdReceiptProof: merkleProof(receipts.map(receiptLeaf), 2),
    verdictStructHash: hashStruct({ data: verdict, primaryType: "SessionVerdict", types: TYPES.SessionVerdict }),
    verdictDigest: hashTypedData({
      domain,
      types: TYPES.SessionVerdict,
      primaryType: "SessionVerdict",
      message: verdict,
    }),
    attestationDigest: hashTypedData({
      domain: scorerDomain(v.chainId, v.escrow),
      types: TYPES.ScoreAttestation,
      primaryType: "ScoreAttestation",
      message: att,
    }),
    policyStructHash: hashStruct({ data: policy, primaryType: "Policy", types: TYPES.Tighten }),
  };
}
