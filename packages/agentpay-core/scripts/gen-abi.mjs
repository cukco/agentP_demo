// Generates src/abi.ts from Foundry output. Run after `forge build` in contracts/.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../../contracts/out/IAgentPaySessionEscrow.sol/IAgentPaySessionEscrow.json");
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
const out = `// AUTO-GENERATED by scripts/gen-abi.mjs from contracts/src/interfaces/IAgentPaySessionEscrow.sol. Do not edit.
export const agentPaySessionEscrowAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
writeFileSync(resolve(here, "../src/abi.ts"), out);
console.log(`abi.ts: ${abi.length} entries`);
